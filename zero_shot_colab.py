print(f'Loaded {len(data)} test examples')

print('Loading model...')
tokenizer = AutoTokenizer.from_pretrained(MODEL)
model = AutoModelForSequenceClassification.from_pretrained(
    MODEL,
    num_labels=len(VALID_FALLACIES),
    id2label=id2label,
    label2id=label2id
)

pipe = pipeline(
    'text-classification',
    model=model,
    tokenizer=tokenizer,
    device=0 if torch.cuda.is_available() else -1
)
print('Model loaded')

print('\n' + '='*70)
print('ZERO-SHOT EVALUATION')
print('='*70 + '\n')

y_true = []
y_pred = []
results = []
inference_times = []

for i, item in enumerate(data):
    argument = item['input']
    true_label = item['output']['fallacy']

    start = time.perf_counter()
    response = pipe(argument)
    end = time.perf_counter()
    runtime = end - start

    predicted_label_id = int(response[0]['label'].split('_')[1])
    predicted_label = id2label[predicted_label_id]
    confidence = response[0]['score']

    results.append({
        'id': i + 1,
        'argument': argument,
        'true_label': true_label,
        'predicted_label': predicted_label,
        'confidence': float(confidence),
        'runtime_seconds': runtime
    })

    y_true.append(true_label)
    y_pred.append(predicted_label)
    inference_times.append(runtime)

    match = '✓' if predicted_label == true_label else '✗'
    print(f"{match} {i+1:2d}. {argument[:50]}...")
    print(f"    True: {true_label:30s} | Pred: {predicted_label:30s} ({confidence:.1%})\n")

