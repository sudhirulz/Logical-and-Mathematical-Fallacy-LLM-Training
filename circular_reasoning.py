label_counts = Counter(train_labels_list)
print(f"  - Circular Reasoning: {label_counts[1]}")
print(f"  - Not Circular Reasoning: {label_counts[0]}\n")

# Calculate class weights
total = len(train_labels_list)
class_weights = torch.tensor([total / (len(VALID_LABELS) * label_counts[i]) for i in range(len(VALID_LABELS))], device=device)
print(f"Class weights: {class_weights}\n")

print("="*70)
print("FINE-TUNING (10 epochs)")
print("="*70 + "\n")

optimizer = torch.optim.AdamW(model.parameters(), lr=1e-5)
model.train()

EPOCHS = 10
BATCH_SIZE = 4
num_batches = (len(train_labels_list) + BATCH_SIZE - 1) // BATCH_SIZE

for epoch in range(EPOCHS):
    total_loss = 0
    for batch_idx in range(num_batches):
        start_idx = batch_idx * BATCH_SIZE
        end_idx = min(start_idx + BATCH_SIZE, len(train_labels_list))

        batch_inputs = {k: v[start_idx:end_idx] for k, v in inputs.items()}
        batch_labels = labels[start_idx:end_idx]

        optimizer.zero_grad()
        outputs = model(**batch_inputs, labels=batch_labels)
        loss = outputs.loss

        # Apply class weights
        logits = outputs.logits
        weighted_loss = F.cross_entropy(logits, batch_labels, weight=class_weights)

        weighted_loss.backward()
        optimizer.step()
        total_loss += weighted_loss.item()

        if (batch_idx + 1) % 3 == 0:
            print(f"Epoch {epoch+1}/{EPOCHS}, Batch {batch_idx+1}/{num_batches}, Loss: {weighted_loss.item():.4f}")

    avg_loss = total_loss / num_batches
    print(f"Epoch {epoch+1} Average Loss: {avg_loss:.4f}\n")

print("✓ Fine-tuning complete!\n")

