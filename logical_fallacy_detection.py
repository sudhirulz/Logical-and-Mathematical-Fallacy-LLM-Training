"""## STEP 2: Import Libraries & Check GPU"""

import json
import torch
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from transformers import (
    AutoTokenizer,
    AutoModelForSequenceClassification,
    Trainer,
    TrainingArguments,
    pipeline
)
from datasets import Dataset
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix
)

# Check GPU
print("GPU Available:", torch.cuda.is_available())
if torch.cuda.is_available():
    print("GPU Device:", torch.cuda.get_device_name(0))

"""## STEP 3: Load Training Data

Option A: Use the sample data below
Option B: Upload your JSON file
"""

# OPTION A: Use sample data
training_data = [
    {"input": "If it rains, the ground gets wet. The ground is wet. Therefore, it rained.", "output": {"fallacy": "Affirming the Consequent"}},
    {"input": "I met two rude tourists from Country X. Therefore, everyone from Country X is rude.", "output": {"fallacy": "Hasty Generalization"}},
    {"input": "Nature intended humans to eat meat. Humans should eat meat.", "output": {"fallacy": "Appeal to Nature"}},
    {"input": "I'm a true Scotsman and I don't support Scottish independence. So anyone who supports independence isn't a true Scotsman.", "output": {"fallacy": "No True Scotsman"}},
    {"input": "I drew a circle and drew 5 random dots inside it, then drew circles around them all. I've discovered a pattern in random dots.", "output": {"fallacy": "Texas Sharpshooter"}},
    {"input": "If someone is a doctor, they have a medical degree. John has a medical degree. Therefore, John is a doctor.", "output": {"fallacy": "Affirming the Consequent"}},
    {"input": "I tried three different diets and they all failed. Therefore, no diet works.", "output": {"fallacy": "Hasty Generalization"}},
    {"input": "Herbal medicine is natural, so it's better than pharmaceutical medicine.", "output": {"fallacy": "Appeal to Nature"}},
    {"input": "Christians are supposed to be peaceful. That Christian supported war. Therefore, he's not a true Christian.", "output": {"fallacy": "No True Scotsman"}},
    {"input": "A man eats almonds on Mondays and wins the lottery twice. Eating almonds on Mondays is a winning lottery strategy.", "output": {"fallacy": "Texas Sharpshooter"}},
]

# OPTION B: Upload your own data
# Uncomment below to upload
# from google.colab import files
# uploaded = files.upload()
# with open('logical_fallacies_mini.json') as f:
#     training_data = json.load(f)

print(f"✓ Loaded {len(training_data)} training examples")
print(f"\nFirst example:")
print(f"  Input: {training_data[0]['input']}")
print(f"  Fallacy: {training_data[0]['output']['fallacy']}")

"""## STEP 4: Setup Label Mapping"""

# Define fallacy types
fallacy_types = [
    "Affirming the Consequent",
    "Hasty Generalization",
    "Appeal to Nature",
    "No True Scotsman",
    "Texas Sharpshooter"
]

label2id = {label: idx for idx, label in enumerate(fallacy_types)}
id2label = {idx: label for label, idx in label2id.items()}

print("📋 Fallacy Types:")
for label, id in label2id.items():
    print(f"  {id}: {label}")

"""## STEP 5: ZERO-SHOT TESTING (Before Fine-Tuning)

Test pretrained model without any fine-tuning
"""

print("\n" + "="*80)
print("ZERO-SHOT TESTING (Untrained Model)")
print("="*80 + "\n")

zero_shot_pipeline = pipeline(
    "zero-shot-classification",
    model="facebook/bart-large-mnli"
)

zero_shot_predictions = []
zero_shot_labels = []

for item in training_data:
    text = item["input"]
    true_label = item["output"]["fallacy"]

    result = zero_shot_pipeline(
        text,
        fallacy_types,
        multi_class=False
    )

    predicted_label = result["labels"][0]
    confidence = result["scores"][0]

    zero_shot_predictions.append(predicted_label)
    zero_shot_labels.append(true_label)

    match = "✓" if predicted_label == true_label else "✗"
    print(f"{match} {text[:60]}...")
    print(f"  True: {true_label} | Predicted: {predicted_label} ({confidence:.2f})\n")

# Calculate accuracy
zero_shot_accuracy = accuracy_score(zero_shot_labels, zero_shot_predictions)
print(f"\n🎯 ZERO-SHOT ACCURACY: {zero_shot_accuracy:.2%}")
print("\nClassification Report:")
print(classification_report(zero_shot_labels, zero_shot_predictions))

"""## STEP 6: Prepare Dataset for Fine-Tuning"""

print("\n" + "="*80)
print("PREPARING DATA FOR FINE-TUNING")
print("="*80 + "\n")

# Create Hugging Face dataset
texts = [item["input"] for item in training_data]
labels = [label2id[item["output"]["fallacy"]] for item in training_data]

dataset = Dataset.from_dict({
    "text": texts,
    "label": labels
})

# Split into train/validation (80/20)
split_dataset = dataset.train_test_split(test_size=0.2, seed=42)
train_dataset = split_dataset["train"]
eval_dataset = split_dataset["test"]

print(f"Training samples: {len(train_dataset)}")
print(f"Validation samples: {len(eval_dataset)}")

# Tokenize
model_name = "distilbert-base-uncased"
tokenizer = AutoTokenizer.from_pretrained(model_name)

def tokenize_function(examples):
    return tokenizer(
        examples["text"],
        padding="max_length",
        truncation=True,
        max_length=128
    )

train_dataset = train_dataset.map(tokenize_function, batched=True)
eval_dataset = eval_dataset.map(tokenize_function, batched=True)

print("\n✓ Data prepared and tokenized")

"""## STEP 7: Load Model and Configure Training"""

print("\n" + "="*80)
print("LOADING MODEL AND CONFIGURING TRAINING")
print("="*80 + "\n")

model = AutoModelForSequenceClassification.from_pretrained(
    model_name,
    num_labels=5,
    id2label=id2label,
    label2id=label2id
)

training_args = TrainingArguments(
    output_dir="./logical_fallacy_model",
    num_train_epochs=3,
    per_device_train_batch_size=8,
    per_device_eval_batch_size=8,
    warmup_steps=50,
    weight_decay=0.01,
    logging_dir="./logs",
    logging_steps=5,
    eval_strategy="epoch",
    save_strategy="epoch",
    load_best_model_at_end=True,
)

# Define metrics function
def compute_metrics(eval_pred):
    logits, labels = eval_pred
    predictions = np.argmax(logits, axis=-1)

    accuracy = accuracy_score(labels, predictions)
    precision = precision_score(labels, predictions, average="weighted", zero_division=0)
    recall = recall_score(labels, predictions, average="weighted", zero_division=0)
    f1 = f1_score(labels, predictions, average="weighted", zero_division=0)

    return {
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1": f1,
    }

# Create trainer
trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_dataset,
    eval_dataset=eval_dataset,
    compute_metrics=compute_metrics,
)

print("✓ Model and trainer configured")

"""## STEP 8: Fine-Tune the Model

⚠️ This will take a few minutes...
"""

print("\n" + "="*80)
print("FINE-TUNING MODEL (3 epochs)")
print("="*80 + "\n")

train_result = trainer.train()

print("\n✓ Training complete!")
print(f"Final training loss: {train_result.training_loss:.4f}")

"""## STEP 9: Test Fine-Tuned Model"""

print("\n" + "="*80)
print("TESTING FINE-TUNED MODEL")
print("="*80 + "\n")

fine_tuned_pipeline = pipeline(
    "text-classification",
    model=model,
    tokenizer=tokenizer,
    device=0 if torch.cuda.is_available() else -1
)

fine_tuned_predictions = []
fine_tuned_labels = []

for item in training_data:
    text = item["input"]
    true_label = item["output"]["fallacy"]

    result = fine_tuned_pipeline(text)
    predicted_label_id = int(result[0]["label"].split("_")[1])
    predicted_label = id2label[predicted_label_id]
    confidence = result[0]["score"]

    fine_tuned_predictions.append(predicted_label)
    fine_tuned_labels.append(true_label)

    match = "✓" if predicted_label == true_label else "✗"
    print(f"{match} {text[:60]}...")
    print(f"  True: {true_label} | Predicted: {predicted_label} ({confidence:.2f})\n")

# Calculate accuracy
fine_tuned_accuracy = accuracy_score(fine_tuned_labels, fine_tuned_predictions)
print(f"\n🎯 FINE-TUNED ACCURACY: {fine_tuned_accuracy:.2%}")
print("\nClassification Report:")
print(classification_report(fine_tuned_labels, fine_tuned_predictions))

"""## STEP 10: Compare Zero-Shot vs Fine-Tuned"""

print("\n" + "="*80)
print("COMPARISON: ZERO-SHOT vs FINE-TUNED")
print("="*80 + "\n")

comparison_df = pd.DataFrame({
    "Model": ["Zero-Shot", "Fine-Tuned"],
    "Accuracy": [zero_shot_accuracy, fine_tuned_accuracy],
})

print(comparison_df.to_string(index=False))
print(f"\n📈 Improvement: +{(fine_tuned_accuracy - zero_shot_accuracy):.2%}")

# Visualize
fig, ax = plt.subplots(figsize=(8, 5))
colors = ["#FF6B6B" if acc < fine_tuned_accuracy else "#4ECDC4" for acc in comparison_df["Accuracy"]]
ax.bar(comparison_df["Model"], comparison_df["Accuracy"], color=colors, edgecolor="black", linewidth=2)
ax.set_ylabel("Accuracy", fontsize=12, fontweight="bold")
ax.set_title("Zero-Shot vs Fine-Tuned Model Performance", fontsize=14, fontweight="bold")
ax.set_ylim([0, 1])
for i, v in enumerate(comparison_df["Accuracy"]):
    ax.text(i, v + 0.05, f"{v:.1%}", ha="center", fontweight="bold", fontsize=12)
plt.tight_layout()
plt.show()

"""## STEP 11: Save Model"""

model.save_pretrained("./logical_fallacy_model_final")
tokenizer.save_pretrained("./logical_fallacy_model_final")

print("✓ Model saved to ./logical_fallacy_model_final")
print("\nLoad it later with:")
print('  pipeline("text-classification", model="./logical_fallacy_model_final")')

"""## STEP 12: Interactive Testing with Custom Examples"""

def test_fallacy(text):
    """Test a custom argument"""
    result = fine_tuned_pipeline(text)
    predicted_label_id = int(result[0]["label"].split("_")[1])
    predicted_label = id2label[predicted_label_id]
    confidence = result[0]["score"]

    return predicted_label, confidence

# Test custom examples
test_examples = [
    "If you study hard, you pass the exam. You passed the exam. So you studied hard.",
    "I saw three homeless people asking for money. All homeless people are beggars.",
    "Animals don't wear clothes. Humans shouldn't wear clothes.",
    "My cousin quit college and succeeded. College is useless.",
    "I found that people born in March are leaders."
]

print("\n" + "="*80)
print("TESTING CUSTOM EXAMPLES")
print("="*80 + "\n")

for example in test_examples:
    predicted, confidence = test_fallacy(example)
    print(f"📝 Text: {example}")
    print(f"🎯 Predicted: {predicted} ({confidence:.1%})\n")

"""## STEP 13: Confusion Matrix"""

cm = confusion_matrix(fine_tuned_labels, fine_tuned_predictions, labels=fallacy_types)
cm_df = pd.DataFrame(cm, index=fallacy_types, columns=fallacy_types)

plt.figure(figsize=(10, 8))
sns.heatmap(cm_df, annot=True, fmt="d", cmap="Blues", cbar=True,
            cbar_kws={'label': 'Count'}, linewidths=0.5)
plt.title("Confusion Matrix - Fine-Tuned Model", fontsize=14, fontweight="bold")
plt.ylabel("True Label", fontsize=12, fontweight="bold")
plt.xlabel("Predicted Label", fontsize=12, fontweight="bold")
plt.xticks(rotation=45, ha='right')
plt.yticks(rotation=0)
plt.tight_layout()
plt.show()

